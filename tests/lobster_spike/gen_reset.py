#!/usr/bin/env python3
# Writes gen/reset.lobster: reset_world() puts every global of the sim (lib/) and the match setup
# (gen/setup, gen/start) back as declared, so one process can set up and play many worlds (the
# balance fights, a new match after a lobby). Run after adding a global: python3 gen_reset.py
import re, os, glob

here = os.path.dirname(os.path.abspath(__file__))
files = sorted(glob.glob(os.path.join(here, 'lib', '*.lobster'))) + [os.path.join(here, 'gen', 'setup.lobster'), os.path.join(here, 'gen', 'start.lobster')]
out = ['// Generated by gen_reset.py: every global of lib/ and gen/setup, gen/start as declared.', '', 'def reset_world():']
for f in files:
    name = os.path.relpath(f, here)
    lines = []
    for line in open(f):
        m = re.match(r'^var (\w+)(?::[^=]+)? = (.*?)\s*(//.*)?$', line.rstrip('\n'))
        if m:
            lines.append('    %s = %s' % (m.group(1), m.group(2)))
            continue
        m = re.match(r'^let (\w+) = (dictionary<[^>]+>\(\d+\))', line)
        if m:
            lines.append('    %s.clear()' % m.group(1))
    if lines:
        out.append('    // ' + name)
        out += lines
open(os.path.join(here, 'gen', 'reset.lobster'), 'w').write('\n'.join(out) + '\n')
print('gen/reset.lobster:', sum(1 for l in out if l.startswith('    ') and not l.startswith('    //')), 'globals')
