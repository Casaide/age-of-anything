#!/usr/bin/env python3
# Writes gen/reset.lobster:
#   reset_world() puts every global of the sim (lib/) and the match setup (gen/setup, gen/start) back
#   as declared, so one process can set up and play many worlds (the balance fights, a new match);
#   stash_world() / unstash_world() set the running world aside and bring it back exactly (each
#   global's value moved, not copied: reset_world makes new containers), so fights can run mid-match.
#   gen/save.lobster: save_world(path) / load_world(path) write and read every one of those globals (one
#   WorldSave record, a flexbuffer), for saving a match.
# Run after adding a global: python3 gen_reset.py
import re, os, glob

here = os.path.dirname(os.path.abspath(__file__))
files = sorted(glob.glob(os.path.join(here, 'lib', '*.lobster'))) + [os.path.join(here, 'gen', 'setup.lobster'), os.path.join(here, 'gen', 'start.lobster')]
reset = ['def reset_world():']
decl = []
stash = ['def stash_world():']
unstash = ['def unstash_world():']
n = 0
fields = []
lets = []   # let dictionaries: cleared on reset, refilled on load
def type_of(ty, init):
    if ty: return ty[1:].strip()
    if re.match(r'^-?\d+$', init): return 'int'
    if init in ('true', 'false'): return 'bool'
    if init == '""': return 'string'
    if init == 'jobj()': return 'JV'
    if init == 'new_rng(1)': return 'Rng'
    m = re.match(r'^\[\]::(.*)$', init)
    if m: return '[%s]' % m.group(1)
    if re.match(r'^\[ ?-?\d+(, -?\d+)* ?\]$', init): return '[int]'
    m = re.match(r'^(dictionary<.*>)\(\d+\)$', init)
    if m: return m.group(1)
    raise Exception('no type for ' + init)
for f in files:
    name = os.path.relpath(f, here)
    r = []
    for line in open(f):
        m = re.match(r'^var (\w+)(:[^=]+)? = (.*?)\s*(//.*)?$', line.rstrip('\n'))
        if m:
            v, ty, init = m.group(1), m.group(2), m.group(3)
            r.append('    %s = %s' % (v, init))
            decl.append('var stashed_%s%s = %s' % (v, ty or '', init))
            stash.append('    stashed_%s = %s' % (v, v))
            unstash.append('    %s = stashed_%s' % (v, v))
            fields.append((v, type_of(ty, init)))
            n += 1
            continue
        m = re.match(r'^let (\w+) = (dictionary<[^>]+>\(\d+\))', line)
        if m:
            r.append('    %s.clear()' % m.group(1))
            lets.append((m.group(1), m.group(2)[:m.group(2).rindex('(')]))
    if r:
        reset.append('    // ' + name)
        reset += r
out = ['// Generated by gen_reset.py: every global of lib/ and gen/setup, gen/start as declared.', ''] + decl + [''] + reset + [''] + stash + [''] + unstash
open(os.path.join(here, 'gen', 'reset.lobster'), 'w').write('\n'.join(out) + '\n')
print('gen/reset.lobster:', n, 'globals')
save = ['// Generated by gen_reset.py: a match saved and loaded, every global of lib/ and gen/setup, gen/start.',
        '', 'class WorldSave:']
save += ['    %s:%s' % (v, t) for v, t in fields]
save += ['    %s:%s' % (v, t) for v, t in lets]
save += ['    bots:[Bot]  // the bots (the game keeps them)']
save += ['', '// The world and the bots as bytes (a save file, or the start of a network match).', 'def world_bytes(bots:[Bot]) -> string:', '    let w = WorldSave {']
save += ['        %s,' % v for v, t in fields + lets] + ['        bots }']
save += ['    return flexbuffers_value_to_binary(w, 1000)', '',
         'def save_world(path:string, bots:[Bot]) -> bool: return write_file(path, world_bytes(bots))', '',
         'def load_world(path:string) -> [Bot]:', '    let data = read_file(path, true)', '    return if data: load_world_bytes(data) else: []', '',
         '// The bots that came with it, or [] if these are not a saved world.', 'def load_world_bytes(data:string) -> [Bot]:',
         '    let w, err = flexbuffers_binary_to_value(typeof WorldSave, data)', '    if err: return []', '    let s = w', '    if not s: return []']
save += ['    %s = s.%s' % (v, v) for v, t in fields]
save += ['    %s.clear()' % v for v, t in lets]
save += ['    s.%s.forkv() k, v: %s.set(k, v)' % (v, v) for v, t in lets]
save += ['    pad_saved_columns()  // (a save from an older build: its missing per-unit and per-building columns, D-141)',
         '    roles_from_data()  // (... and its building types\' roles, D-192)',
         '    spatial_clear()  // (... and its spatial buckets, which an older build filled over the whole map)', '    return s.bots']
open(os.path.join(here, 'gen', 'save.lobster'), 'w').write('\n'.join(save) + '\n')
# Both files in the formatter's layout, so `./lint.sh` stays clean after a run.
import subprocess
subprocess.run([os.path.expanduser('~/Dev/lobster/bin/lobsterfmt'), '-w', '-program', os.path.join(here, 'game.lobster'),
                os.path.join(here, 'gen', 'reset.lobster'), os.path.join(here, 'gen', 'save.lobster')], check=True)
